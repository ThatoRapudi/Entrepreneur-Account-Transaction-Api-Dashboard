# Pydantic Models - Request/Response Validation
# Validates data entering and leaving the API
from pydantic import BaseModel
from datetime import datetime
from typing import Optional, List

# ============================================================================
# ACCOUNT SCHEMAS
# ============================================================================

class AccountBase(BaseModel):
    # Base account data - shared between create and response. These are the core fields every account has.
    business_name: str
    owner_name: str
    industry: str
    status: str = "active"

class AccountCreate(AccountBase):
    # Schema for creating a new account.
    # Client sends this when: POST /accounts
    #Why separate from AccountBase- Create doesn't need id (auto-generated by database)and Create doesn't need timestamps (auto-generated)
    pass


class AccountUpdate(BaseModel):
    """
    Schema for updating an account.
    Client sends this when: PUT /accounts/{id}
    
    Why Optional:
    - Client might only update business_name, not industry
    - All fields are optional (update what you need)
    """
    business_name: Optional[str] = None
    status: Optional[str] = None
    lifecycle_stage: Optional[str] = None


class AccountResponse(AccountBase):
    """
    Schema for API response when returning an account.
    API sends this when: GET /accounts/{id}
    
    Why different from AccountCreate:
    - Includes id, timestamps, calculated fields
    - Client receives read-only info (churn_risk_score, days_since_open)
    """
    id: int
    account_id: str
    opening_date: datetime
    lifecycle_stage: str
    days_since_open: int
    churn_risk_score: float
    monthly_turnover: Optional[float] = None
    created_at: datetime
    updated_at: datetime

    class Config:
        from_attributes = True  # Allow reading from SQLAlchemy models


# ============================================================================
# POS TRANSACTION SCHEMAS
# ============================================================================

class POSTransactionBase(BaseModel):
    """Base POS transaction data."""
    amount: float
    transaction_type: str  # "airtime", "electricity", "voucher"
    description: str
    merchant: str
    payment_method: Optional[str] = None  # tap_to_pay, scan_to_pay, card_swipe, mobile_wallet
    card_type: Optional[str] = None  # debit, credit


class POSTransactionCreate(POSTransactionBase):
    """
    Schema for recording a new POS transaction.
    Client sends: POST /transactions/pos
    """
    account_id: str


class POSTransactionResponse(POSTransactionBase):
    """
    Schema for API response with transaction details.
    API sends: GET /transactions/{id}
    """
    id: int
    account_id: str
    transaction_id: str
    transaction_date: datetime
    created_at: datetime

    class Config:
        from_attributes = True


