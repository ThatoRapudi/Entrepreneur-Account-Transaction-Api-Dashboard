class LoanBase(BaseModel):
    """Base loan data."""
    amount: float
    status: str = "applied"
    loan_term: Optional[str] = None  # short_term, medium_term, long_term
    term_months: Optional[int] = None


class LoanCreate(LoanBase):
    """
    Schema for applying for a loan.
    Client sends: POST /loans
    """
    account_id: str


class LoanResponse(LoanBase):
    """
    Schema for API response with loan details.
    API sends: GET /loans/{id}
    """
    id: int
    account_id: str
    loan_id: str
    application_date: datetime
    approval_date: Optional[datetime] = None
    disbursement_date: Optional[datetime] = None

    class Config:
        from_attributes = True

class LoanUpdate(BaseModel):
    """
    Schema for updating a loan.
    Client sends this when: PUT /api/loans/{loan_id}
    """
    amount: Optional[float] = None  # Modify loan amount
    status: Optional[str] = None  # Update status
    qualified: Optional[bool] = None  # Add this: qualified or not
    loan_term: Optional[str] = None
    term_months: Optional[int] = None


